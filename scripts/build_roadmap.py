def build_html(
    doc: dict[str, Any],
    schedule: dict[str, Any],
    cards: list[dict[str, str]] | None = None,
    lessons: dict[str, Any] | None = None,
) -> str:
    """Render the single-page app.

    Everything the page shows is computed here from the curriculum, the review
    schedule and the flashcard deck. The page itself invents nothing: if a number
    is not derivable from these three inputs, it is not displayed.
    """
    entries = schedule.get("topics") or {}
    phases_out = []
    for phase in iter_phases(doc):
        topics_out = []
        for topic in phase["topics"]:
            topics_out.append({
                "id": topic["id"],
                "slug": topic["slug"],
                "title": topic["title"],
                "summary": topic["summary"],
                "order": topic["order"],
                "status": topic["status"],
                "source": topic["source"],
                "prerequisites": topic.get("prerequisites", []),
                "estimated_minutes": topic["estimated_minutes"],
                "learning_objectives": topic["learning_objectives"],
                "lesson_path": topic["lesson_path"],
                "quiz_path": topic["quiz_path"],
                "scaffolded": topic["scaffolded"],
                "project_links": topic.get("project_links", []),
                "evidence": topic.get("evidence", {}),
            })
        phases_out.append({
            "id": phase["id"],
            "title": phase["title"],
            "description": phase["description"],
            "order": phase["order"],
            "status": phase["status"],
            "flowchart": phase_topic_flowchart(phase),
            "topics": topics_out,
        })

    mastery = doc.get("mastery_policy") or {}
    tracks = doc.get("tracks") or {}
    progress_policy = doc.get("progress_policy") or {}
    payload = {
        "phases": phases_out,
        "projects": doc.get("projects", []),
        "project_names": {p["id"]: p["name"] for p in doc.get("projects", [])},
        # Review state is owned by tracker/review_schedule.json. The page reads it
        # and never writes it, so scripts/review.py stays the single writer.
        "reviews": {tid: entry for tid, entry in entries.items()},
        "cards": cards or [],
        "lessons": lessons or {},
        "flowchart": phase_flowchart(doc),
        "meta": {
            "phase_count": len(phases_out),
            "tracks": [
                {"name": f"Track {key}: {value.get('name', '')}",
                 "description": value.get("description", "")}
                for key, value in sorted(tracks.items())
            ],
            "mastery_conditions": mastery.get("conditions", []),
            "quiz_threshold": mastery.get("quiz_threshold_percent", {}),
            "foundational_phases": mastery.get("foundational_phases", []),
            "progress_definition": progress_policy.get("topic_completion", ""),
        },
    }
    data = json.dumps(payload, indent=None, separators=(",", ":"), sort_keys=False)
    # Defensive: never let a closing script tag appear inside the data block.
    data = data.replace("</", "<\\/")

    total_topics = sum(len(p["topics"]) for p in phases_out)
    attribution = doc.get("attribution") or {}
    return (
        HTML_TEMPLATE
        .replace("__PHASE_COUNT__", str(len(phases_out)))
        .replace("__TOPIC_COUNT__", str(total_topics))
        .replace("__CREDIT__", CREDIT)
        .replace("__FETCH_DATE__", str(attribution.get("structure_fetched_on", "unknown")))
        .replace("__DATA__", data)
    )


