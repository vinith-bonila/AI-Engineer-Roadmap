"""Generate the roadmap artefacts from roadmap/curriculum.json.

Outputs:
  roadmap/roadmap.mmd           full Mermaid flowchart, every topic, every prerequisite edge
  roadmap/roadmap-overview.mmd  phase-level Mermaid flowchart, embedded in the README
  roadmap/roadmap.html          self-contained interactive roadmap, works over file://

Both Mermaid files and the HTML are derived from the same JSON in the same run, so
they cannot disagree. Nothing is written if validation fails, and the exit code is
nonzero. Running the script twice without editing the JSON produces byte-identical
output: no timestamps are emitted.

Usage:
  python scripts/build_roadmap.py [--check]

  --check  validate and report without writing any file
"""
