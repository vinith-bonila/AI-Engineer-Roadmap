def normalise_phase_statuses(doc: dict[str, Any]) -> list[str]:
    """Recompute derived phase statuses. Returns the phases that changed."""
    changed = []
    for phase in iter_phases(doc):
        derived = derive_phase_status(phase.get("topics", []))
        if phase.get("status") != derived:
            changed.append(f"{phase['id']}: {phase.get('status')} -> {derived}")
            phase["status"] = derived
    return changed


def check_output_parity(doc: dict[str, Any], mmd: str, html: str) -> list[str]:
    """Every topic must appear exactly once in each output. Catches silent drops."""
    problems = []
    for _, topic in iter_topics(doc):
        node = mermaid_id(topic["id"])
        count = mmd.count(f'{node}["')
        if count != 1:
            problems.append(
                f"topic {topic['id']} appears {count} times as a node in roadmap.mmd, expected 1"
            )
        if html.count('"' + topic["id"] + '"') < 1:
            problems.append(f"topic {topic['id']} is missing from roadmap.html")
    return problems


def check_lesson_links(doc: dict[str, Any], root: Path) -> list[str]:
    problems = []
    for _, topic in iter_topics(doc):
        if topic.get("scaffolded") and not (root / topic["lesson_path"]).is_file():
            problems.append(
                f"topic {topic['id']}: linked lesson {topic['lesson_path']} does not exist"
            )
    return problems


def update_readme(root: Path, overview: str) -> str:
    """Replace the generated block in README.md. Returns a status message."""
    readme = root / "README.md"
    if not readme.is_file():
        return "README.md not found, skipped the embedded diagram"
    text = readme.read_text(encoding="utf-8")
    if README_BEGIN not in text or README_END not in text:
        return "README.md has no generated-overview markers, skipped"
    block = (
        README_BEGIN
        + "\n\n```mermaid\n"
        + overview.strip()
        + "\n```\n\n"
        + README_END
    )
    start = text.index(README_BEGIN)
    end = text.index(README_END) + len(README_END)
    new_text = text[:start] + block + text[end:]
    if new_text == text:
        return "README.md embedded diagram already up to date"
    readme.write_text(new_text, encoding="utf-8", newline="\n")
    return "README.md embedded diagram updated"


def write_if_changed(path: Path, content: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="validate only, write nothing")
    parser.add_argument("--root", help="repository root to operate on (default: auto-detect)")
    args = parser.parse_args(argv)

    try:
        root = Path(args.root) if args.root else repo_root()
        doc = load_curriculum(root)
        schedule = load_review_schedule(root)
        cards = load_cards(root)
    except CurriculumError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    changed_phases = normalise_phase_statuses(doc)

    result = validate(doc, root)
    review_result = validate_review_schedule(doc, schedule)
    errors = result.errors + review_result.errors
    warnings = result.warnings + review_result.warnings

    if errors:
        print(f"FAILED: {len(errors)} validation error(s) in roadmap/curriculum.json",
              file=sys.stderr)
        for message in errors:
            print(f"  - {message}", file=sys.stderr)
        print("\nNothing was written. Fix the JSON and run the build again.",
              file=sys.stderr)
        return 1

    projects = {p["id"]: p["name"] for p in doc.get("projects", [])}
    mmd_full = build_mermaid_full(doc, projects)
    mmd_overview = build_mermaid_overview(doc)
    lessons = collect_lessons(doc, root)
    html = build_html(doc, schedule, cards, lessons)

    parity = check_output_parity(doc, mmd_full, html)
    links = check_lesson_links(doc, root)
    if parity or links:
        print("FAILED: generated output did not pass its own checks", file=sys.stderr)
        for message in parity + links:
            print(f"  - {message}", file=sys.stderr)
        return 1

    n_phases = len(doc["phases"])
    n_topics = sum(len(p["topics"]) for p in doc["phases"])
    progress = overall_progress(doc)
    index = topic_index(doc)
    edges = sum(len(t.get("prerequisites", [])) for t in index.values())

    if args.check:
        print("check only, nothing written")
    else:
        written = []
        for relpath, content in (
            ("roadmap/roadmap.mmd", mmd_full),
            ("roadmap/roadmap-overview.mmd", mmd_overview),
            ("roadmap/roadmap.html", html),
        ):
            if write_if_changed(root / relpath, content):
                written.append(relpath)
            else:
                print(f"unchanged: {relpath}")
        for relpath in written:
            print(f"wrote:     {relpath}")
        if changed_phases:
            curriculum_path = root / "roadmap" / "curriculum.json"
            curriculum_path.write_text(
                json.dumps(doc, indent=2, ensure_ascii=True) + "\n",
                encoding="utf-8", newline="\n",
            )
            print("wrote:     roadmap/curriculum.json (derived phase statuses)")
            for message in changed_phases:
                print(f"           {message}")
        print(update_readme(root, mmd_overview))

    print()
    print(f"phases:      {n_phases}")
    print(f"topics:      {n_topics}")
    print(f"prereq edges: {edges}")
    print(f"scaffolded:  {sum(1 for t in index.values() if t.get('scaffolded'))}")
    print(f"progress:    {progress.done}/{progress.total} topics "
          f"({progress.topic_percent:.1f}%), effort weighted "
          f"{progress.effort_percent:.1f}% of {progress.minutes_total / 60:.0f} lesson hours")
    for warning in warnings:
        print(f"warning:     {warning}")
    print("validation:  passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
